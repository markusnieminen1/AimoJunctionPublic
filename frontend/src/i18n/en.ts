type Widen<T> = T extends (...args: infer A) => string
  ? (...args: A) => string
  : T extends readonly { readonly code: string; readonly label: string }[]
    ? readonly { readonly code: string; readonly label: string }[]
    : T extends readonly { readonly label: string; readonly prompt: string }[]
      ? readonly { readonly label: string; readonly prompt: string }[]
      : T extends readonly string[]
      ? readonly string[]
      : T extends Record<string, unknown>
        ? { readonly [K in keyof T]: Widen<T[K]> }
        : T extends string
          ? string
          : T;

